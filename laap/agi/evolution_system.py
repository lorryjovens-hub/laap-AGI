"""
LAAP AGI — Evolution System Integration (进化系统)

Bridges RSI (Recursive Self-Improvement) and AEvo (Agent Evolution)
into the AGI framework.

Capabilities:
  - Self-modification proposals (RSI)
  - Sandbox testing of changes
  - 4-zone rollout (monitor → test → rollout → production)
  - Metrics-driven fitness evaluation
  - Rollback on degradation
  - Symbolic reasoning engine for code mutations

This enables the agent to genuinely IMPROVE ITS OWN CODE over time,
not just accumulate skills — it can rewrite its own strategies.
"""

from __future__ import annotations

import logging

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Set, Tuple, Callable
import time, logging, json, threading
from collections import defaultdict

logger = logging.getLogger("laap.agi.evolution")


@dataclass
class EvolutionProposal:
    """A self-improvement proposal generated by RSI."""
    id: str = ""
    description: str = ""
    target_module: str = ""
    change_type: str = "optimization"  # optimization, fix, feature, refactor
    expected_improvement: float = 0.1
    risk_level: float = 0.3
    status: str = "draft"  # draft → testing → approved → deployed → rolled_back
    created_at: float = field(default_factory=time.time)
    test_results: Dict[str, Any] = field(default_factory=dict)
    deployment_zone: int = 1  # 1=monitor, 2=test, 3=rollout, 4=production


class EvolutionSystem:
    """
    Self-evolution engine for AGI agent.

    Enables the agent to propose, test, and deploy improvements to itself.
    """

    def __init__(self, name: str = "evolution"):
        self.name = name
        self.created_at = time.time()

        self.proposals: List[EvolutionProposal] = []
        self.total_proposals = 0
        self.total_deployments = 0
        self.total_rollbacks = 0

        # RSI engine reference (lazy)
        self._rsi_engine: Any = None

        # AEvo reference (lazy)
        self._aevo: Any = None

        # Metrics
        self._metrics: Dict[str, List[float]] = defaultdict(list)
        self._fitness_history: List[float] = []

        # Deployment zones
        self._zone_stats = {1: 0, 2: 0, 3: 0, 4: 0}

        self._lock = threading.Lock()
        self._init_backends()

    def _init_backends(self):
        """Connect to existing evolution backends."""
        try:
            from laap.evolution.rsi import RSIEngine
            self._rsi_engine = RSIEngine()
            logger.debug("RSI engine loaded")
        except (ImportError, TypeError):
            pass  # 可选模块，降级处理
        try:
            from laap.evolution.aevo.harness import Harness
            self._aevo = Harness()
            logger.debug("AEvo harness loaded")
        except (ImportError, TypeError):
            pass  # 可选模块，降级处理
        try:
            from laap.engine.evolution.metrics_collector import MetricsCollector
            self._metrics_collector = MetricsCollector()
            logger.debug("Metrics collector loaded")
        except (ImportError, TypeError):
            self._metrics_collector = None

    # ════════════════════════════════════════════════════════
    # Proposal Generation
    # ════════════════════════════════════════════════════════

    def generate_proposal(self, description: str,
                          target: str = "agent_strategy",
                          change_type: str = "optimization",
                          expected_improvement: float = 0.1,
                          risk: float = 0.3) -> EvolutionProposal:
        """Generate a self-improvement proposal."""
        with self._lock:
            self.total_proposals += 1
            proposal = EvolutionProposal(
                id=f"evo_{self.total_proposals}",
                description=description,
                target_module=target,
                change_type=change_type,
                expected_improvement=expected_improvement,
                risk_level=risk,
            )
            self.proposals.append(proposal)

            if self._rsi_engine:
                try:
                    self._rsi_engine.register_proposal(description, target)
                except Exception as e:
                    logger.debug(f"操作失败: {e}")
            return proposal

    def evaluate_proposal(self, proposal_id: str,
                          fitness_before: float,
                          fitness_after: float) -> Dict[str, Any]:
        """Evaluate a proposal's effect on fitness."""
        with self._lock:
            improvement = fitness_after - fitness_before
            self._fitness_history.append(fitness_after)

            for p in self.proposals:
                if p.id == proposal_id:
                    p.test_results = {
                        "fitness_before": fitness_before,
                        "fitness_after": fitness_after,
                        "improvement": improvement,
                        "evaluated_at": time.time(),
                    }

                    if improvement > 0:
                        p.status = "approved"
                        if p.risk_level < 0.3:
                            p.deployment_zone = 3
                        else:
                            p.deployment_zone = 2
                    else:
                        p.status = "rejected"

                    return {
                        "proposal_id": proposal_id,
                        "improvement": improvement,
                        "approved": improvement > 0,
                        "zone": p.deployment_zone,
                    }

            return {"error": "Proposal not found"}

    def deploy_proposal(self, proposal_id: str) -> Dict[str, Any]:
        """Deploy an approved proposal."""
        with self._lock:
            for p in self.proposals:
                if p.id == proposal_id:
                    if p.status != "approved":
                        return {"error": f"Proposal not approved (status={p.status})"}

                    p.status = "deployed"
                    zone = p.deployment_zone
                    self._zone_stats[zone] = self._zone_stats.get(zone, 0) + 1
                    self.total_deployments += 1
                    return {
                        "deployed": True,
                        "proposal_id": proposal_id,
                        "zone": zone,
                        "description": p.description[:100],
                    }
            return {"error": "Proposal not found"}

    def rollback(self, proposal_id: str, reason: str = "") -> Dict[str, Any]:
        """Rollback a deployed proposal."""
        with self._lock:
            for p in self.proposals:
                if p.id == proposal_id:
                    p.status = "rolled_back"
                    self.total_rollbacks += 1
                    return {
                        "rolled_back": True,
                        "proposal_id": proposal_id,
                        "reason": reason,
                    }
            return {"error": "Proposal not found"}

    # ════════════════════════════════════════════════════════
    # Metrics
    # ════════════════════════════════════════════════════════

    def record_metric(self, name: str, value: float):
        """Record a performance metric."""
        with self._lock:
            self._metrics[name].append(value)
            # Keep last 1000
            if len(self._metrics[name]) > 1000:
                self._metrics[name] = self._metrics[name][-1000:]

    def get_metric_trend(self, name: str, window: int = 10) -> Dict[str, Any]:
        """Get trend analysis for a metric."""
        values = self._metrics.get(name, [])
        if len(values) < window:
            return {"name": name, "trend": "insufficient_data"}

        recent = values[-window:]
        earlier = values[-window*2:-window] if len(values) >= window*2 else values[:window]

        recent_avg = sum(recent) / len(recent)
        earlier_avg = sum(earlier) / len(earlier) if earlier else recent_avg

        diff = recent_avg - earlier_avg
        trend = "improving" if diff > 0.05 else "declining" if diff < -0.05 else "stable"

        return {
            "name": name,
            "trend": trend,
            "recent_avg": round(recent_avg, 3),
            "change": round(diff, 3),
            "samples": len(values),
        }

    def current_fitness(self) -> float:
        """Get current fitness score."""
        if self._fitness_history:
            return self._fitness_history[-1]
        return 0.5

    # ════════════════════════════════════════════════════════
    # Stats
    # ════════════════════════════════════════════════════════

    def stats(self) -> Dict[str, Any]:
        with self._lock:
            approved = sum(1 for p in self.proposals if p.status == "approved")
            deployed = sum(1 for p in self.proposals if p.status == "deployed")
            rolled = sum(1 for p in self.proposals if p.status == "rolled_back")

            return {
                "name": self.name,
                "total_proposals": self.total_proposals,
                "approved": approved,
                "deployed": deployed,
                "rolled_back": rolled,
                "current_fitness": round(self.current_fitness(), 3),
                "zone_distribution": self._zone_stats,
                "metrics_tracked": len(self._metrics),
                "uptime_seconds": time.time() - self.created_at,
            }


def integrate_evolution_system(agent) -> EvolutionSystem:
    evo = EvolutionSystem(name=f"{getattr(agent, 'name', 'agent')}-evo")
    agent.evolution = evo
    logger.info(f"EvolutionSystem integrated into {getattr(agent, 'name', 'agent')}")
    return evo
